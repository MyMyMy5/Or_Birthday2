// ==================== UNDO/REDO HISTORY STACK ====================

/**
 * HistoryStack — records edit operations and supports undo/redo.
 * Edit_Operation shape: { type: string, target: string, key: string, oldValue: any, newValue: any, timestamp: number }
 */
var HistoryStack = {
    _undoStack: [],
    _redoStack: [],

    /**
     * Record a new edit operation. Clears the redo stack.
     * @param {Object} operation - An Edit_Operation object.
     */
    push: function (operation) {
        this._undoStack.push(operation);
        this._redoStack = [];
    },

    /**
     * Undo the most recent operation.
     * Moves the operation from the undo stack to the redo stack.
     * @returns {Object|null} The undone Edit_Operation, or null if nothing to undo.
     */
    undo: function () {
        if (this._undoStack.length === 0) return null;
        var operation = this._undoStack.pop();
        this._redoStack.push(operation);
        return operation;
    },

    /**
     * Redo the most recently undone operation.
     * Moves the operation from the redo stack to the undo stack.
     * @returns {Object|null} The redone Edit_Operation, or null if nothing to redo.
     */
    redo: function () {
        if (this._redoStack.length === 0) return null;
        var operation = this._redoStack.pop();
        this._undoStack.push(operation);
        return operation;
    },

    /**
     * @returns {boolean} True if there are operations that can be undone.
     */
    canUndo: function () {
        return this._undoStack.length > 0;
    },

    /**
     * @returns {boolean} True if there are operations that can be redone.
     */
    canRedo: function () {
        return this._redoStack.length > 0;
    },

    /**
     * Clear both undo and redo stacks.
     * Called when Edit Mode deactivates.
     */
    clear: function () {
        this._undoStack = [];
        this._redoStack = [];
    }
};

