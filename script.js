function setupLightbox() {
    var overlay = document.getElementById('lightbox');
    if (!overlay) return;

    var closeBtn = overlay.querySelector('.lightbox-close');
    if (closeBtn) {
        closeBtn.addEventListener('click', closeLightbox);
    }

    // Wire arrow button click handlers
    var prevBtn = overlay.querySelector('.lightbox-prev');
    var nextBtn = overlay.querySelector('.lightbox-next');
    if (prevBtn) {
        prevBtn.addEventListener('click', lightboxPrev);
    }
    if (nextBtn) {
        nextBtn.addEventListener('click', lightboxNext);
    }

    // Backdrop click: close if clicking the overlay itself, not the content
    overlay.addEventListener('click', function (e) {
        if (e.target === overlay) {
            closeLightbox();
        }
    });

    // Document-level keydown listener for arrow keys and Escape
    document.addEventListener('keydown', function (e) {
        if (!lightboxOpen) return;
        if (e.key === 'Escape') {
            closeLightbox();
        } else if (e.key === 'ArrowRight') {
            lightboxNext();
        } else if (e.key === 'ArrowLeft') {
            lightboxPrev();
        }
    });

    // Wire photo card clicks via event delegation on the photos grid
    var photosGrid = document.getElementById('photos-grid');
    if (photosGrid) {
        photosGrid.addEventListener('click', function (e) {
            // Check if the clicked element is a zoomable img inside a non-video photo card
            var target = e.target;
            if (!target.matches || !target.matches('img.zoomable')) return;
            var card = target.closest('.photo-card');
            if (!card || card.classList.contains('video-card')) return;

            // Find the index of this photo among all visible photo-card images
            var allImages = photosGrid.querySelectorAll('.photo-card:not(.video-card) img.zoomable');
            var index = Array.prototype.indexOf.call(allImages, target);
            if (index >= 0) {
                openLightbox(index);
            }
        });
    }

    // Set up swipe gesture support for touch devices
    setupLightboxSwipe();
}

function openLightbox(photoIndex) {
    // Collect all visible photo card images from the grid
    var photosGrid = document.getElementById('photos-grid');
    if (!photosGrid) return;

    var images = photosGrid.querySelectorAll('.photo-card:not(.video-card) img.zoomable');
    if (!images || images.length === 0) return; // Guard against empty gallery

    lightboxPhotos = [];
    for (var i = 0; i < images.length; i++) {
        lightboxPhotos.push({
            url: images[i].src,
            caption: images[i].alt || ''
        });
    }

    if (lightboxPhotos.length === 0) return; // Guard against empty gallery

    lightboxIndex = photoIndex;
    if (lightboxIndex < 0 || lightboxIndex >= lightboxPhotos.length) {
        lightboxIndex = 0;
    }

    lightboxOpen = true;

    var overlay = document.getElementById('lightbox');
    if (overlay) {
        overlay.classList.add('active');
        overlay.setAttribute('aria-hidden', 'false');

        // Show/hide arrow buttons based on gallery size
        var prevBtn = overlay.querySelector('.lightbox-prev');
        var nextBtn = overlay.querySelector('.lightbox-next');
        if (prevBtn) {
            prevBtn.style.display = lightboxPhotos.length <= 1 ? 'none' : '';
        }
        if (nextBtn) {
            nextBtn.style.display = lightboxPhotos.length <= 1 ? 'none' : '';
        }
    }

    // Set aria-hidden on main content
    var mainContent = document.getElementById('memories-page');
    if (mainContent) {
        mainContent.setAttribute('aria-hidden', 'true');
    }

    updateLightboxDisplay();
}

function closeLightbox() {
    var overlay = document.getElementById('lightbox');
    if (overlay) {
        overlay.classList.remove('active');
        overlay.setAttribute('aria-hidden', 'true');
    }

    // Restore main content accessibility
    var mainContent = document.getElementById('memories-page');
    if (mainContent) {
        mainContent.removeAttribute('aria-hidden');
    }

    lightboxOpen = false;
}

function updateLightboxDisplay() {
    if (!lightboxPhotos.length) return;

    var img = document.getElementById('lightbox-img');
    var counter = document.querySelector('.lightbox-counter');

    if (img) {
        img.src = lightboxPhotos[lightboxIndex].url;
        img.alt = lightboxPhotos[lightboxIndex].caption;
    }

    if (counter) {
        counter.textContent = (lightboxIndex + 1) + ' / ' + lightboxPhotos.length;
    }
}

/**
 * Navigate to the next photo in the lightbox with wrap-around.
 */
function lightboxNext() {
    if (!lightboxOpen || lightboxPhotos.length <= 1) return;
    lightboxIndex = (lightboxIndex + 1) % lightboxPhotos.length;
    updateLightboxDisplay();
}

/**
 * Navigate to the previous photo in the lightbox with wrap-around.
 */
function lightboxPrev() {
    if (!lightboxOpen || lightboxPhotos.length <= 1) return;
    lightboxIndex = (lightboxIndex - 1 + lightboxPhotos.length) % lightboxPhotos.length;
    updateLightboxDisplay();
}

/**
 * Set up swipe gesture detection on the lightbox overlay.
 * Swipe left → next photo, swipe right → previous photo.
 * Requires minimum 50px horizontal distance and rejects vertical-dominant swipes.
 */
function setupLightboxSwipe() {
    var lightboxEl = document.getElementById('lightbox');
    if (!lightboxEl) return;
    var touchStartX = 0;
    var touchStartY = 0;

    lightboxEl.addEventListener('touchstart', function (e) {
        touchStartX = e.changedTouches[0].clientX;
        touchStartY = e.changedTouches[0].clientY;
    }, { passive: true });

    lightboxEl.addEventListener('touchend', function (e) {
        var dx = e.changedTouches[0].clientX - touchStartX;
        var dy = e.changedTouches[0].clientY - touchStartY;
        if (Math.abs(dy) > Math.abs(dx)) return; // Vertical dominates — reject
        if (Math.abs(dx) < 50) return; // Below minimum threshold
        if (dx < 0) lightboxNext();
        else lightboxPrev();
    }, { passive: true });
}

