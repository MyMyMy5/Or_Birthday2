/**
 * Reads the hidden_sections array from localStorage.
 * @returns {string[]} Array of hidden section IDs
 */
function getHiddenSections() {
    try {
        var raw = localStorage.getItem('hidden_sections');
        if (raw) {
            var parsed = JSON.parse(raw);
            if (Array.isArray(parsed)) {
                return parsed;
            }
        }
    } catch (e) {
        // Invalid JSON or localStorage unavailable
    }
    return [];
}

/**
 * Saves the hidden_sections array to localStorage.
 * @param {string[]} hiddenIds - Array of hidden section IDs
 */
function saveHiddenSections(hiddenIds) {
    try {
        localStorage.setItem('hidden_sections', JSON.stringify(hiddenIds));
    } catch (e) {
        // localStorage unavailable — silently fail
    }
}

/**
 * Returns all section IDs currently in the DOM.
 * @returns {string[]}
 */
function getAllSectionIds() {
    var container = document.querySelector('.memories-content');
    if (!container) return [];
    var sections = container.querySelectorAll('.section');
    var ids = [];
    for (var i = 0; i < sections.length; i++) {
        if (sections[i].id) {
            ids.push(sections[i].id);
        }
    }
    return ids;
}

/**
 * Hides a section: collapses its content and shows a minimal hidden indicator.
 * In edit mode, the indicator is visible with a "Show" button.
 * Outside edit mode, the section is completely invisible.
 * @param {string} sectionId - The ID of the section to hide
 */
function hideSection(sectionId) {
    var section = document.getElementById(sectionId);
    if (!section) return;

    // Mark the section as hidden
    section.classList.add('section-hidden');

    // Hide all children except the hidden indicator (if it exists)
    var children = section.children;
    for (var i = 0; i < children.length; i++) {
        if (!children[i].classList.contains('section-hidden-indicator')) {
            children[i].style.display = 'none';
        }
    }

    // Create hidden indicator if it doesn't exist
    if (!section.querySelector('.section-hidden-indicator')) {
        var indicator = createHiddenIndicator(sectionId, section);
        section.appendChild(indicator);
    }
}

/**
 * Shows a section: restores its content and removes the hidden indicator.
 * @param {string} sectionId - The ID of the section to show
 */
function showSection(sectionId) {
    var section = document.getElementById(sectionId);
    if (!section) return;

    // Remove hidden class
    section.classList.remove('section-hidden');

    // Show all children
    var children = section.children;
    for (var i = 0; i < children.length; i++) {
        if (children[i].classList.contains('section-hidden-indicator')) {
            section.removeChild(children[i]);
            i--; // Adjust index after removal
        } else {
            children[i].style.display = '';
        }
    }
}

/**
 * Creates the minimal hidden indicator bar for a hidden section.
 * Shows section name and a "Show" button (visible only in edit mode via CSS).
 * @param {string} sectionId - The section ID
 * @param {HTMLElement} section - The section element
 * @returns {HTMLElement} The indicator element
 */
function createHiddenIndicator(sectionId, section) {
    var indicator = document.createElement('div');
    indicator.className = 'section-hidden-indicator';

    // Get section name from the title element (which is now hidden)
    var titleEl = section.querySelector('.section-title');
    var sectionName = titleEl ? titleEl.textContent : sectionId.replace('-section', '');

    var nameSpan = document.createElement('span');
    nameSpan.className = 'section-hidden-name';
    nameSpan.textContent = '👁️‍🗨️ ' + sectionName + ' (hidden)';

    var showBtn = document.createElement('button');
    showBtn.className = 'section-show-btn';
    showBtn.textContent = 'Show Section';
    showBtn.addEventListener('click', function () {
        var oldHidden = getHiddenSections().slice(); // copy for undo

        // Show the section
        showSection(sectionId);

        // Remove from hidden list in localStorage
        var hidden = getHiddenSections();
        var idx = hidden.indexOf(sectionId);
        if (idx !== -1) {
            hidden.splice(idx, 1);
            saveHiddenSections(hidden);
        }

        // Re-inject the settings panel for this section if in edit mode
        if (document.body.classList.contains('dev-mode-active')) {
            var sec = document.getElementById(sectionId);
            if (sec && !sec.querySelector('.section-settings-panel')) {
                var panel = createSectionSettingsPanel(sectionId);
                sec.insertBefore(panel, sec.firstChild);
                wireSectionColorPicker(panel, sectionId);
                wireSectionLayoutToggle(panel, sectionId);
                wireSectionColumnSelector(panel, sectionId);
                wireSectionMoveButtons(panel, sectionId);
                wireSectionHideButton(panel, sectionId);
            }
            updateAllMoveButtonStates();
            updateAllHideButtonStates();
        }

        recordEditOperation('hide', sectionId, 'hidden_sections', oldHidden, getHiddenSections().slice());
    });

    indicator.appendChild(nameSpan);
    indicator.appendChild(showBtn);

    return indicator;
}

/**
 * Wires the hide button in a section settings panel.
 * @param {HTMLElement} panel - The .section-settings-panel element
 * @param {string} sectionId - The ID of the section
 */
function wireSectionHideButton(panel, sectionId) {
    var hideBtn = panel.querySelector('.ssp-hide-btn');
    if (!hideBtn) return;

    hideBtn.addEventListener('click', function () {
        var allIds = getAllSectionIds();
        var hidden = getHiddenSections();
        var oldHidden = hidden.slice(); // copy for undo

        // Prevent hiding all sections — at least one must remain visible
        var visibleCount = allIds.filter(function (id) {
            return hidden.indexOf(id) === -1;
        }).length;

        if (visibleCount <= 1) {
            alert('At least one section must remain visible.');
            return;
        }

        // Add to hidden list
        if (hidden.indexOf(sectionId) === -1) {
            hidden.push(sectionId);
            saveHiddenSections(hidden);
        }

        // Hide the section
        hideSection(sectionId);

        // Update hide button states across all panels
        updateAllHideButtonStates();

        recordEditOperation('hide', sectionId, 'hidden_sections', oldHidden, hidden.slice());
    });
}

