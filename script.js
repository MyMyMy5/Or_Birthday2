/**
 * Clamps a value to the valid column range (2–6).
 * @param {number} value - The value to clamp
 * @returns {number} Clamped integer between 2 and 6
 */
function clampColumnCount(value) {
    var num = parseInt(value, 10);
    if (isNaN(num) || num < 2) return 2;
    if (num > 6) return 6;
    return num;
}

/**
 * Applies a column count to a section's item container via CSS custom property.
 * @param {string} sectionId - The section ID
 * @param {number} count - Column count (2–6)
 */
function applySectionColumnCount(sectionId, count) {
    var container = getSectionItemContainer(sectionId);
    if (!container) return;
    var clamped = clampColumnCount(count);
    container.style.setProperty('--grid-columns', clamped);
}

