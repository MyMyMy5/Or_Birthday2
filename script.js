window.HistoryStack = HistoryStack;

// ==================== UNDO/REDO INTEGRATION HELPERS ====================

/**
 * Records an edit operation in the HistoryStack.
 * Only records when Edit Mode is active.
 * @param {string} type - Operation type (e.g., 'inline-edit', 'color-change', 'layout-change', 'pin', 'hide', 'reorder', 'filter', 'frame', 'tag-add', 'tag-delete')
 * @param {string} target - The section or item ID affected
 * @param {string} key - The localStorage key affected
 * @param {*} oldValue - The value before the operation
 * @param {*} newValue - The value after the operation
 */
function recordEditOperation(type, target, key, oldValue, newValue) {
    if (!document.body.classList.contains('dev-mode-active')) return;
    HistoryStack.push({
        type: type,
        target: target,
        key: key,
        oldValue: oldValue,
        newValue: newValue,
        timestamp: Date.now()
    });
}

/**
 * Applies an undo operation: restores oldValue to localStorage and updates DOM.
 * @param {Object} operation - The Edit_Operation to undo
 */
function applyUndoOperation(operation) {
    if (!operation) return;
    _applyOperationValue(operation.key, operation.target, operation.oldValue, operation.type);
}

/**
 * Applies a redo operation: restores newValue to localStorage and updates DOM.
 * @param {Object} operation - The Edit_Operation to redo
 */
function applyRedoOperation(operation) {
    if (!operation) return;
    _applyOperationValue(operation.key, operation.target, operation.newValue, operation.type);
}

/**
 * Internal helper: writes a value to localStorage for the given key/target and refreshes DOM.
 * Handles both map-style keys (where target is a sub-key) and array-style keys (like hidden_sections).
 * @param {string} key - localStorage key
 * @param {string} target - The section or item ID
 * @param {*} value - The value to write (or null to remove the entry)
 * @param {string} type - The operation type (used to determine DOM refresh strategy)
 */
function _applyOperationValue(key, target, value, type) {
    try {
        if (type === 'hide') {
            // hidden_sections is stored as an array, not a map
            localStorage.setItem(key, JSON.stringify(value));
        } else if (type === 'pin') {
            // pinned_items is a map of sectionId -> itemId, stored as full object
            localStorage.setItem(key, JSON.stringify(value));
        } else if (type === 'reorder') {
            // developer_mode_order is a map of sectionKey -> array of IDs
            var orderMap = {};
            try {
                orderMap = JSON.parse(localStorage.getItem(key) || '{}');
            } catch (e) { /* ignore */ }
            if (value === null || value === undefined) {
                delete orderMap[target];
            } else {
                orderMap[target] = value;
            }
            localStorage.setItem(key, JSON.stringify(orderMap));
        } else {
            // Default: map-style storage (key -> { target: value })
            var raw = localStorage.getItem(key);
            var store = raw ? JSON.parse(raw) : {};

            if (value === null || value === undefined) {
                delete store[target];
            } else {
                store[target] = value;
            }

            localStorage.setItem(key, JSON.stringify(store));
        }
    } catch (e) {
        // Silently fail on localStorage errors
    }

    // Refresh DOM based on operation type
    _refreshDomForOperation(key, target, type);
}

/**
 * Refreshes the DOM after an undo/redo operation.
 * Calls existing render/apply functions based on the operation type.
 * @param {string} key - localStorage key
 * @param {string} target - The section or item ID
 * @param {string} type - The operation type
 */
function _refreshDomForOperation(key, target, type) {
    switch (type) {
        case 'inline-edit':
            if (key === 'section_titles') {
                var titleEl = document.querySelector('#' + target + ' .section-title');
                if (titleEl) {
                    try {
                        var titles = JSON.parse(localStorage.getItem('section_titles') || '{}');
                        if (titles[target]) {
                            titleEl.textContent = titles[target];
                        }
                    } catch (e) { /* ignore */ }
                }
            } else if (key === 'song_renames' || key === 'photo_renames') {
                var el = document.querySelector('[data-id="' + target + '"] .editable-title, [data-id="' + target + '"] .song-title');
                if (el) {
                    try {
                        var renames = JSON.parse(localStorage.getItem(key) || '{}');
                        if (renames[target]) {
                            el.textContent = renames[target];
                        }
                    } catch (e) { /* ignore */ }
                }
            }
            break;

        case 'color-change':
            applySavedSectionColors();
            break;

        case 'layout-change':
            applySavedSectionLayouts();
            break;

        case 'pin':
            // Re-apply pinned state for all sections since the full map was restored
            applyAllPinnedStates();
            break;

        case 'hide':
            // Re-apply hidden sections: first show all, then re-hide from stored list
            var allSections = document.querySelectorAll('.section');
            for (var i = 0; i < allSections.length; i++) {
                if (allSections[i].classList.contains('section-hidden')) {
                    showSection(allSections[i].id);
                }
            }
            applySavedHiddenSections();
            updateHiddenSectionsVisibility();
            break;

        case 'reorder':
            // Re-apply saved order for the target section
            if (key === 'developer_mode_order') {
                try {
                    var orderMap = JSON.parse(localStorage.getItem('developer_mode_order') || '{}');
                    var orderedIds = orderMap[target];
                    if (orderedIds && Array.isArray(orderedIds)) {
                        var section = document.getElementById(target);
                        if (section) {
                            var SECTION_ITEM_CONTAINERS_MAP = {
                                'photos-section': '#photos-grid',
                                'songs-section': '.songs-list',
                                'likes-section': '.likes-grid',
                                'funny-moments-section': '#funny-moments-grid'
                            };
                            var sel = SECTION_ITEM_CONTAINERS_MAP[target];
                            var container = sel ? section.querySelector(sel) : null;
                            if (container) {
                                orderedIds.forEach(function (id) {
                                    var item = container.querySelector('[data-id="' + id + '"]');
                                    if (item) container.appendChild(item);
                                });
                            }
                        }
                    }
                } catch (e) { /* ignore */ }
            }
            break;

        case 'filter':
            applySavedPhotoFilters();
            break;

        case 'frame':
            applySavedPhotoFrames();
            break;

        case 'tag-add':
        case 'tag-delete':
            renderAllPhotoTags();
            break;

        default:
            break;
    }
}

