/**
 * Shows an inline form to add an item to a custom section.
 * @param {string} sectionId - The custom section ID.
 * @param {string} itemType - 'text', 'image', or 'link'.
 * @param {HTMLElement} itemsContainer - The container to append new items to.
 * @param {HTMLElement} addBtn - The add button element (to insert form before it).
 */
function showCustomSectionAddForm(sectionId, itemType, itemsContainer, addBtn) {
    // Don't show multiple forms
    if (itemsContainer.querySelector('.custom-section-add-form')) return;

    var form = document.createElement('div');
    form.className = 'custom-section-add-form';

    var input = document.createElement(itemType === 'text' ? 'textarea' : 'input');
    input.className = 'custom-section-add-input';

    if (itemType === 'text') {
        input.placeholder = 'Enter text...';
        input.rows = 3;
    } else if (itemType === 'image') {
        input.type = 'text';
        input.placeholder = 'Enter image URL...';
    } else if (itemType === 'link') {
        input.type = 'url';
        input.placeholder = 'Enter link URL...';
    }

    var btnRow = document.createElement('div');
    btnRow.className = 'custom-section-add-form-actions';

    var submitBtn = document.createElement('button');
    submitBtn.className = 'custom-section-add-submit';
    submitBtn.textContent = 'Add';

    var cancelBtn = document.createElement('button');
    cancelBtn.className = 'custom-section-add-cancel';
    cancelBtn.textContent = 'Cancel';

    btnRow.appendChild(submitBtn);
    btnRow.appendChild(cancelBtn);

    form.appendChild(input);
    form.appendChild(btnRow);

    // Insert form before the add button
    itemsContainer.insertBefore(form, addBtn);

    input.focus();

    function submitItem() {
        var content = input.value.trim();
        if (!content) {
            form.parentNode.removeChild(form);
            return;
        }

        var item = {
            id: generateCustomItemId(),
            content: content
        };

        var success = addItemToCustomSection(sectionId, item);
        if (success) {
            var itemEl = renderCustomSectionItem(item, itemType);
            if (itemEl) {
                itemsContainer.insertBefore(itemEl, addBtn);
            }
        }

        form.parentNode.removeChild(form);
    }

    submitBtn.addEventListener('click', submitItem);
    cancelBtn.addEventListener('click', function () {
        form.parentNode.removeChild(form);
    });

    // Submit on Enter for single-line inputs
    if (itemType !== 'text') {
        input.addEventListener('keydown', function (e) {
            if (e.key === 'Enter') {
                e.preventDefault();
                submitItem();
            }
        });
    }
}

/**
 * Render a single item within a custom section.
 * @param {Object} item - The item object with id and content.
 * @param {string} itemType - 'text', 'image', or 'link'.
 * @returns {HTMLElement|null} The created item element.
 */
function renderCustomSectionItem(item, itemType) {
    if (!item || !item.content) return null;

    var itemEl = document.createElement('div');
    itemEl.className = 'custom-section-item';
    itemEl.setAttribute('data-item-id', item.id || '');

    if (itemType === 'text') {
        var textEl = document.createElement('p');
        textEl.className = 'custom-item-text';
        textEl.textContent = item.content;
        if (item.caption) {
            var captionEl = document.createElement('span');
            captionEl.className = 'custom-item-caption';
            captionEl.textContent = item.caption;
            textEl.appendChild(captionEl);
        }
        itemEl.appendChild(textEl);
    } else if (itemType === 'image') {
        var imgEl = document.createElement('img');
        imgEl.className = 'custom-item-image';
        imgEl.src = item.content;
        imgEl.alt = item.caption || 'Custom image';
        imgEl.loading = 'lazy';
        itemEl.appendChild(imgEl);
        if (item.caption) {
            var capEl = document.createElement('p');
            capEl.className = 'custom-item-caption';
            capEl.textContent = item.caption;
            itemEl.appendChild(capEl);
        }
    } else if (itemType === 'link') {
        var linkEl = document.createElement('a');
        linkEl.className = 'custom-item-link';
        linkEl.href = item.content;
        linkEl.textContent = item.caption || item.content;
        linkEl.target = '_blank';
        linkEl.rel = 'noopener noreferrer';
        itemEl.appendChild(linkEl);
    }

    return itemEl;
}

/**
 * Render all custom sections after the built-in sections.
 * Called on page load.
 */
function renderAllCustomSections() {
    var sections = getCustomSections();
    if (sections.length === 0) return;

    // Find the container that holds all sections (the .memories-content parent of built-in sections)
    var sectionsContainer = document.querySelector('.memories-content');
    if (!sectionsContainer) {
        // Fallback: find the parent of the last built-in section
        var funnySection = document.getElementById('funny-section');
        if (funnySection && funnySection.parentNode) {
            sectionsContainer = funnySection.parentNode;
        }
    }
    if (!sectionsContainer) return;

    // Remove any previously rendered custom sections to avoid duplicates
    var existingCustomSections = sectionsContainer.querySelectorAll('.custom-section');
    for (var i = 0; i < existingCustomSections.length; i++) {
        existingCustomSections[i].parentNode.removeChild(existingCustomSections[i]);
    }

    // Render each custom section
    sections.forEach(function (sectionDef) {
        var sectionEl = renderCustomSection(sectionDef);
        sectionsContainer.appendChild(sectionEl);
    });
}

