/**
 * Makes an element inline-editable when Edit Mode is active.
 * On click: replaces textContent with an <input> (or <textarea> if options.multiline).
 * On Enter/blur: saves to localStorage and updates display.
 * On Escape: discards changes and reverts to original text.
 * Empty strings are not saved (reverts to original).
 *
 * @param {HTMLElement} element - The DOM element to make editable
 * @param {Object} options
 * @param {string} options.storageKey - localStorage key (e.g. 'song_renames')
 * @param {string} options.itemId - Unique identifier for the item
 * @param {string} [options.field] - Sub-field within the item (e.g. 'name', 'artist')
 * @param {boolean} [options.multiline] - Use textarea instead of input
 * @param {string} [options.placeholder] - Placeholder text for the input
 */
function makeInlineEditable(element, options) {
    if (!element) return;

    var storageKey = options.storageKey;
    var itemId = options.itemId;
    var field = options.field || null;
    var multiline = options.multiline || false;
    var placeholder = options.placeholder || '';

    element.addEventListener('click', function (e) {
        // Only activate when edit mode is active
        if (!document.body.classList.contains('dev-mode-active')) return;

        // Prevent activating if already editing
        if (element.querySelector('input') || element.querySelector('textarea')) return;

        var originalText = element.textContent;

        // Create the input element
        var inputEl;
        if (multiline) {
            inputEl = document.createElement('textarea');
            inputEl.rows = 3;
        } else {
            inputEl = document.createElement('input');
            inputEl.type = 'text';
        }
        inputEl.value = originalText;
        inputEl.className = 'inline-edit-input';
        if (placeholder) {
            inputEl.placeholder = placeholder;
        }

        // Replace element content with input
        element.textContent = '';
        element.appendChild(inputEl);
        inputEl.focus();
        inputEl.select();

        var saved = false;

        function saveEdit() {
            if (saved) return;
            saved = true;

            var newValue = inputEl.value.trim();

            // Prevent saving empty strings — revert to original
            if (!newValue) {
                element.textContent = originalText;
                return;
            }

            // Save to localStorage
            try {
                var raw = localStorage.getItem(storageKey);
                var store = raw ? JSON.parse(raw) : {};

                // Capture old value for undo before modifying
                var oldStoredValue = field ? (store[itemId] && store[itemId][field] || null) : (store[itemId] || null);

                if (field) {
                    if (!store[itemId] || typeof store[itemId] !== 'object') {
                        store[itemId] = {};
                    }
                    store[itemId][field] = newValue;
                } else {
                    store[itemId] = newValue;
                }

                localStorage.setItem(storageKey, JSON.stringify(store));

                // Record for undo/redo (only if value actually changed)
                if (oldStoredValue !== newValue) {
                    recordEditOperation('inline-edit', itemId, storageKey, oldStoredValue, newValue);
                }
            } catch (err) {
                // Silently fail on localStorage errors
            }

            // Update display
            element.textContent = newValue;
        }

        function discardEdit() {
            if (saved) return;
            saved = true;
            element.textContent = originalText;
        }

        // Handle keydown events
        inputEl.addEventListener('keydown', function (ev) {
            if (ev.key === 'Enter' && !multiline) {
                ev.preventDefault();
                saveEdit();
            } else if (ev.key === 'Enter' && multiline && ev.ctrlKey) {
                ev.preventDefault();
                saveEdit();
            } else if (ev.key === 'Escape') {
                ev.preventDefault();
                discardEdit();
            }
        });

        // Handle blur (save on focus loss)
        inputEl.addEventListener('blur', function () {
            saveEdit();
        });

        // Prevent the click from bubbling (e.g., triggering parent handlers)
        e.stopPropagation();
    });
}

