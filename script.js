/**
 * Generate a thumbnail from a video source by capturing the first frame.
 * Uses an off-screen <video> + <canvas> to draw the frame at currentTime = 0.1s.
 * @param {string} videoSource - A video file URL or data URL.
 * @returns {Promise<string|null>} Resolves with a data URL of the thumbnail, or null on failure.
 */
function generateVideoThumbnail(videoSource) {
    return new Promise(function (resolve) {
        var video = document.createElement('video');
        video.preload = 'metadata';
        video.muted = true;
        video.playsInline = true;
        video.crossOrigin = 'anonymous';

        var timeoutId = setTimeout(function () {
            cleanup();
            resolve(null);
        }, 10000); // 10 second timeout for safety

        function cleanup() {
            clearTimeout(timeoutId);
            video.removeAttribute('src');
            video.load();
        }

        video.addEventListener('loadeddata', function () {
            video.currentTime = 0.1;
        });

        video.addEventListener('seeked', function () {
            try {
                var canvas = document.createElement('canvas');
                canvas.width = video.videoWidth || 320;
                canvas.height = video.videoHeight || 240;
                var ctx = canvas.getContext('2d');
                ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
                var dataUrl = canvas.toDataURL('image/jpeg', 0.7);
                cleanup();
                resolve(dataUrl);
            } catch (e) {
                cleanup();
                resolve(null);
            }
        });

        video.addEventListener('error', function () {
            cleanup();
            resolve(null);
        });

        video.src = videoSource;
    });
}

