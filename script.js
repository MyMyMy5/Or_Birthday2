/**
 * Show an edit input for an existing tag to rename it.
 * @param {HTMLElement} card - The .photo-card element.
 * @param {string} itemId - The photo item ID.
 * @param {number} tagIndex - The index of the tag being edited.
 * @param {Object} tag - The tag object { x, y, name }.
 */
function showTagEditInput(card, itemId, tagIndex, tag) {
    var input = document.createElement('input');
    input.type = 'text';
    input.className = 'photo-tag-input';
    input.placeholder = 'Tag name';
    input.value = tag.name;
    input.style.left = tag.x + '%';
    input.style.top = tag.y + '%';
    card.appendChild(input);
    input.focus();
    input.select();

    function commitEdit() {
        var newName = input.value.trim();
        if (input.parentNode) {
            input.parentNode.removeChild(input);
        }
        if (newName && newName !== tag.name) {
            // Update the tag name
            var allTags = getPhotoTags();
            if (allTags[itemId] && allTags[itemId][tagIndex]) {
                allTags[itemId][tagIndex].name = newName;
                setPhotoTags(itemId, allTags[itemId]);
            }
        }
        renderPhotoTagsForCard(card);
    }

    input.addEventListener('keydown', function (e) {
        if (e.key === 'Enter') {
            e.preventDefault();
            commitEdit();
        } else if (e.key === 'Escape') {
            e.preventDefault();
            if (input.parentNode) {
                input.parentNode.removeChild(input);
            }
        }
    });

    input.addEventListener('blur', function () {
        commitEdit();
    });
}

