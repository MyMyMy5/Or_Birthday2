// ==================== DRAG-AND-DROP REORDER ENGINE ====================

/**
 * Sets up drag-and-drop reordering for items within a container.
 * Uses the HTML5 Drag and Drop API with CSS transition animations.
 *
 * @param {HTMLElement} container - The DOM element containing the items
 * @param {string} sectionKey - The section identifier string (e.g. 'photos')
 * @param {Object} options
 * @param {string} options.itemSelector - CSS selector for draggable items
 * @param {string} [options.excludeSelector] - CSS selector for non-draggable items
 * @param {string} options.direction - 'grid' or 'vertical'
 * @param {Function} [options.onReorder] - Callback invoked with the new ordered ID array after a drop
 */
function setupSectionReorder(container, sectionKey, options) {
    if (!container) return;

    var itemSelector = options.itemSelector;
    var excludeSelector = options.excludeSelector || '';
    var direction = options.direction || 'vertical';
    var onReorder = options.onReorder || null;

    // State for the current drag operation
    var dragState = {
        draggedEl: null,
        draggedIndex: -1,
        currentDropIndex: -1,
        placeholder: null,
        items: []
    };

    function getReorderableItems() {
        var all = Array.from(container.querySelectorAll(itemSelector));
        if (excludeSelector) {
            all = all.filter(function (el) {
                return !el.matches(excludeSelector);
            });
        }
        return all;
    }

    function getItemIndex(el) {
        return getReorderableItems().indexOf(el);
    }

    // Set draggable on all reorderable items
    var items = getReorderableItems();
    items.forEach(function (item) {
        item.setAttribute('draggable', 'true');
    });

    // --- Event Handlers ---

    function onDragStart(e) {
        var target = e.target.closest(itemSelector);
        if (!target) return;
        if (excludeSelector && target.matches(excludeSelector)) return;

        dragState.items = getReorderableItems();
        dragState.draggedEl = target;
        dragState.draggedIndex = dragState.items.indexOf(target);
        dragState.currentDropIndex = dragState.draggedIndex;

        // Set data transfer
        var itemId = target.getAttribute('data-id') || '';
        e.dataTransfer.setData('text/plain', itemId);
        e.dataTransfer.effectAllowed = 'move';

        // Visual feedback — apply after a microtask so the drag image captures the original look
        requestAnimationFrame(function () {
            target.classList.add('dragging');

            if (direction === 'grid') {
                // For grid: create a placeholder and hide the dragged item
                dragState.placeholder = document.createElement('div');
                dragState.placeholder.className = 'reorder-placeholder';
                // Match the dragged item's approximate size
                var rect = target.getBoundingClientRect();
                dragState.placeholder.style.width = rect.width + 'px';
                dragState.placeholder.style.height = rect.height + 'px';
                target.style.display = 'none';
                target.parentNode.insertBefore(dragState.placeholder, target.nextSibling);
            }
        });
    }

    function onDragOver(e) {
        e.preventDefault();
        e.dataTransfer.dropEffect = 'move';

        if (!dragState.draggedEl) return;

        var items = getReorderableItems();
        var pointerX = e.clientX;
        var pointerY = e.clientY;

        // Find the drop index based on pointer position
        var newDropIndex = items.length; // default: end
        for (var i = 0; i < items.length; i++) {
            var item = items[i];
            if (item === dragState.draggedEl) continue;

            var rect = item.getBoundingClientRect();
            if (direction === 'vertical') {
                var midY = rect.top + rect.height / 2;
                if (pointerY < midY) {
                    newDropIndex = i;
                    break;
                }
            } else {
                // Grid: check both axes
                var midX = rect.left + rect.width / 2;
                var midY = rect.top + rect.height / 2;
                // If pointer is in the top half of the row containing this item
                if (pointerY < rect.bottom && pointerY >= rect.top) {
                    if (pointerX < midX) {
                        newDropIndex = i;
                        break;
                    }
                } else if (pointerY < rect.top) {
                    newDropIndex = i;
                    break;
                }
            }
        }

        // Adjust: if we're past the dragged element's original position, account for it
        if (newDropIndex === dragState.currentDropIndex) return;
        dragState.currentDropIndex = newDropIndex;

        if (direction === 'grid') {
            // For grid layout: move the placeholder to the new position
            if (dragState.placeholder) {
                // Remove placeholder from current position
                if (dragState.placeholder.parentNode) {
                    dragState.placeholder.parentNode.removeChild(dragState.placeholder);
                }
                // Insert at the new drop position
                var visibleItems = Array.from(container.querySelectorAll(itemSelector + ', .reorder-placeholder')).filter(function (el) {
                    return el !== dragState.draggedEl;
                });
                // Filter out excluded items for index calculation but keep them in DOM
                var reorderableVisible = visibleItems.filter(function (el) {
                    if (el.classList.contains('reorder-placeholder')) return true;
                    if (excludeSelector && el.matches(excludeSelector)) return false;
                    return true;
                });

                if (newDropIndex >= reorderableVisible.length) {
                    // Find the last reorderable item or placeholder and insert after it
                    var lastReorderable = reorderableVisible[reorderableVisible.length - 1];
                    if (lastReorderable && lastReorderable.nextSibling) {
                        container.insertBefore(dragState.placeholder, lastReorderable.nextSibling);
                    } else {
                        container.appendChild(dragState.placeholder);
                    }
                } else {
                    var refEl = reorderableVisible[newDropIndex];
                    if (refEl) {
                        container.insertBefore(dragState.placeholder, refEl);
                    }
                }
            }
        } else {
            // For vertical layout: use CSS transforms to shift items
            var draggedRect = dragState.draggedEl.getBoundingClientRect();
            var itemHeight = draggedRect.height;
            // Get the gap between items from computed style
            var containerStyle = window.getComputedStyle(container);
            var gap = parseInt(containerStyle.gap || containerStyle.rowGap || '0', 10) || 8;
            var shiftAmount = itemHeight + gap;

            items.forEach(function (item, i) {
                if (item === dragState.draggedEl) {
                    return;
                }
                var origIndex = i;
                var dragIdx = dragState.draggedIndex;
                var dropIdx = newDropIndex;

                if (dragIdx < dropIdx) {
                    // Dragging downward: items between dragIdx+1 and dropIdx shift up
                    if (origIndex > dragIdx && origIndex <= dropIdx) {
                        item.style.transform = 'translateY(' + (-shiftAmount) + 'px)';
                    } else {
                        item.style.transform = '';
                    }
                } else if (dragIdx > dropIdx) {
                    // Dragging upward: items between dropIdx and dragIdx-1 shift down
                    if (origIndex >= dropIdx && origIndex < dragIdx) {
                        item.style.transform = 'translateY(' + shiftAmount + 'px)';
                    } else {
                        item.style.transform = '';
                    }
                } else {
                    item.style.transform = '';
                }
            });
        }
    }

    function onDrop(e) {
        e.preventDefault();
        e.stopPropagation();

        if (!dragState.draggedEl) return;

        var items = getReorderableItems();

        // Clean up visual state
        cleanupDragVisuals(items);

        // Determine the final order
        var dropIdx = dragState.currentDropIndex;
        var dragIdx = dragState.draggedIndex;

        if (dropIdx !== dragIdx && dropIdx >= 0) {
            // Build the new order by removing the dragged item and inserting at the drop position
            var orderedItems = items.slice();
            var removed = orderedItems.splice(dragIdx, 1)[0];
            // Adjust drop index if it was after the original position
            var insertIdx = dropIdx > dragIdx ? dropIdx - 1 : dropIdx;
            if (insertIdx < 0) insertIdx = 0;
            if (insertIdx > orderedItems.length) insertIdx = orderedItems.length;
            orderedItems.splice(insertIdx, 0, removed);

            // Reorder DOM elements
            orderedItems.forEach(function (item) {
                container.appendChild(item);
            });

            // Re-append excluded items (like add buttons) at the end
            if (excludeSelector) {
                var excluded = Array.from(container.querySelectorAll(excludeSelector));
                excluded.forEach(function (el) {
                    container.appendChild(el);
                });
            }

            // Extract new ID order and save
            var newOrder = orderedItems.map(function (item) {
                return item.getAttribute('data-id');
            }).filter(Boolean);

            // Capture old order for undo before saving
            var oldOrder = getOrderedIds(sectionKey);

            saveOrder(sectionKey, newOrder);

            recordEditOperation('reorder', sectionKey, 'developer_mode_order', oldOrder, newOrder);

            if (onReorder) {
                onReorder(newOrder);
            }
        }

        resetDragState();
    }

    function onDragEnd(e) {
        // Clean up in case drop didn't fire (cancel, escape, drag outside)
        if (!dragState.draggedEl) return;

        var items = getReorderableItems();
        cleanupDragVisuals(items);
        resetDragState();
    }

    function onDragLeave(e) {
        // Only act if we've left the container entirely
        if (!container.contains(e.relatedTarget)) {
            if (!dragState.draggedEl) return;
            var items = getReorderableItems();
            // Reset transforms but keep drag state active (user might come back)
            items.forEach(function (item) {
                item.style.transform = '';
            });
            dragState.currentDropIndex = dragState.draggedIndex;
        }
    }

    function cleanupDragVisuals(items) {
        // Remove transforms from all items
        items.forEach(function (item) {
            item.style.transform = '';
        });

        // Remove dragging class and restore visibility
        if (dragState.draggedEl) {
            dragState.draggedEl.classList.remove('dragging');
            dragState.draggedEl.style.display = '';
        }

        // Remove placeholder
        if (dragState.placeholder && dragState.placeholder.parentNode) {
            dragState.placeholder.parentNode.removeChild(dragState.placeholder);
        }
    }

    function resetDragState() {
        dragState.draggedEl = null;
        dragState.draggedIndex = -1;
        dragState.currentDropIndex = -1;
        dragState.placeholder = null;
        dragState.items = [];
    }

    // --- Attach event listeners to the container ---
    container.addEventListener('dragstart', onDragStart);
    container.addEventListener('dragover', onDragOver);
    container.addEventListener('drop', onDrop);
    container.addEventListener('dragend', onDragEnd);
    container.addEventListener('dragleave', onDragLeave);

    // Store cleanup references on the container for teardown
    container._reorderHandlers = {
        dragstart: onDragStart,
        dragover: onDragOver,
        drop: onDrop,
        dragend: onDragEnd,
        dragleave: onDragLeave
    };
}

/**
 * Tears down drag-and-drop reordering for a container, removing all event
 * listeners and resetting draggable state on items.
 *
 * @param {HTMLElement} container - The DOM element that was set up for reordering
 * @param {Object} options
 * @param {string} options.itemSelector - CSS selector for draggable items
 * @param {string} [options.excludeSelector] - CSS selector for non-draggable items
 */
function teardownSectionReorder(container, options) {
    if (!container) return;

    // Remove stored event listeners
    if (container._reorderHandlers) {
        var events = ['dragstart', 'dragover', 'drop', 'dragend', 'dragleave'];
        events.forEach(function (evt) {
            if (container._reorderHandlers[evt]) {
                container.removeEventListener(evt, container._reorderHandlers[evt]);
            }
        });
        delete container._reorderHandlers;
    }

    var itemSelector = options.itemSelector;
    var excludeSelector = options.excludeSelector || '';

    // Get all reorderable items
    var items = Array.from(container.querySelectorAll(itemSelector));
    if (excludeSelector) {
        items = items.filter(function (el) {
            return !el.matches(excludeSelector);
        });
    }

    // Reset draggable attribute, transforms, and dragging class
    items.forEach(function (item) {
        item.setAttribute('draggable', 'false');
        item.style.transform = '';
        item.classList.remove('dragging');
    });

    // Remove any lingering placeholder elements
    var placeholders = container.querySelectorAll('.reorder-placeholder');
    placeholders.forEach(function (ph) {
        ph.parentNode.removeChild(ph);
    });
}

