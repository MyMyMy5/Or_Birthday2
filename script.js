/**
 * Toggles pin state for an item. Only one item can be pinned per section.
 * @param {string} sectionId - The section ID
 * @param {string} itemId - The item ID to pin/unpin
 */
function togglePinItem(sectionId, itemId) {
    var pinned = getPinnedItems();
    var oldPinned = JSON.parse(JSON.stringify(pinned)); // deep copy for undo

    if (pinned[sectionId] === itemId) {
        // Unpin: clicking on already-pinned item
        delete pinned[sectionId];
    } else {
        // Pin this item (replaces any previously pinned item in same section)
        pinned[sectionId] = itemId;
    }

    savePinnedItems(pinned);
    applyPinnedStateToSection(sectionId);
    recordEditOperation('pin', sectionId, 'pinned_items', oldPinned, JSON.parse(JSON.stringify(pinned)));
}

/**
 * Applies the pinned visual state to all items in a given section.
 * Updates the pin button active state, adds .pinned class and badge,
 * and positions the pinned item first in its container.
 * @param {string} sectionId - The section ID
 */
function applyPinnedStateToSection(sectionId) {
    var pinned = getPinnedItems();
    var pinnedItemId = pinned[sectionId] || null;

    var section = document.getElementById(sectionId);
    if (!section) return;

    // Find the item container for this section
    var containerSelector = SECTION_ITEM_CONTAINERS[sectionId];
    var container = containerSelector ? section.querySelector(containerSelector) : null;

    // Get all items with data-id in this section
    var allItems = section.querySelectorAll('[data-id]');
    var pinnedElement = null;

    for (var i = 0; i < allItems.length; i++) {
        var item = allItems[i];
        var itemId = item.getAttribute('data-id');

        if (itemId === pinnedItemId) {
            // Add pinned class
            item.classList.add('pinned');
            // Add pinned badge if not already present
            if (!item.querySelector('.pinned-badge')) {
                var badge = document.createElement('div');
                badge.className = 'pinned-badge';
                badge.textContent = '⭐ Featured';
                item.insertBefore(badge, item.firstChild);
            }
            pinnedElement = item;
        } else {
            // Remove pinned class and badge from non-pinned items
            item.classList.remove('pinned');
            var existingBadge = item.querySelector('.pinned-badge');
            if (existingBadge) {
                existingBadge.parentNode.removeChild(existingBadge);
            }
        }
    }

    // Position pinned item first in its container
    if (pinnedElement && container && pinnedElement.parentNode === container) {
        var firstChild = container.firstElementChild;
        if (firstChild && firstChild !== pinnedElement) {
            container.insertBefore(pinnedElement, firstChild);
        }
    }

    // Update pin button active states
    var pinButtons = section.querySelectorAll('.pin-item-btn');
    for (var i = 0; i < pinButtons.length; i++) {
        var btn = pinButtons[i];
        var item = btn.closest('[data-id]');
        if (!item) continue;

        var itemId = item.getAttribute('data-id');
        if (itemId === pinnedItemId) {
            btn.classList.add('pinned-active');
        } else {
            btn.classList.remove('pinned-active');
        }
    }
}

/**
 * Applies pinned state to all sections on page load.
 */
function applyAllPinnedStates() {
    var pinned = getPinnedItems();
    var sectionIds = Object.keys(pinned);
    for (var i = 0; i < sectionIds.length; i++) {
        applyPinnedStateToSection(sectionIds[i]);
    }
}

