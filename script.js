/**
 * All localStorage customization keys that should be exported/imported.
 */
var EXPORT_KEYS = [
    'section_titles', 'section_colors', 'section_order', 'section_layouts',
    'section_columns', 'hidden_sections', 'pinned_items', 'item_notes',
    'song_renames', 'photo_renames', 'photo_filters', 'photo_frames',
    'photo_tags', 'video_thumbnails', 'song_thumbnails', 'custom_sections',
    'developer_mode_order', 'media_manager_added', 'media_manager_trash'
];

/**
 * Export all localStorage customization settings to a JSON file download.
 * Collects all EXPORT_KEYS that have non-null values, parses them as JSON,
 * and triggers a browser file download with filename birthday-settings-YYYY-MM-DD.json.
 */
function exportSettings() {
    var data = {};
    for (var i = 0; i < EXPORT_KEYS.length; i++) {
        var key = EXPORT_KEYS[i];
        var value = localStorage.getItem(key);
        if (value !== null) {
            try {
                data[key] = JSON.parse(value);
            } catch (e) {
                // If value is not valid JSON, store as raw string
                data[key] = value;
            }
        }
    }

    var jsonStr = JSON.stringify(data, null, 2);
    var blob = new Blob([jsonStr], { type: 'application/json' });
    var url = URL.createObjectURL(blob);

    var now = new Date();
    var yyyy = now.getFullYear();
    var mm = String(now.getMonth() + 1).padStart(2, '0');
    var dd = String(now.getDate()).padStart(2, '0');
    var filename = 'birthday-settings-' + yyyy + '-' + mm + '-' + dd + '.json';

    var a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

/**
 * Import settings from a JSON file and write to localStorage.
 * Only writes keys that are in the EXPORT_KEYS array for safety.
 * Reloads the page on success. Displays an error for invalid JSON.
 * @param {File} file - The JSON file selected by the user.
 * @returns {Promise<void>}
 */
function importSettings(file) {
    return new Promise(function(resolve, reject) {
        if (!file) {
            reject(new Error('No file provided'));
            return;
        }

        var reader = new FileReader();

        reader.onload = function(e) {
            var content = e.target.result;
            var data;

            try {
                data = JSON.parse(content);
            } catch (parseError) {
                alert('Import failed: The selected file contains invalid JSON.');
                reject(parseError);
                return;
            }

            if (typeof data !== 'object' || data === null || Array.isArray(data)) {
                alert('Import failed: The file format is invalid. Expected a JSON object.');
                reject(new Error('Invalid format: not a JSON object'));
                return;
            }

            var keys = Object.keys(data);
            for (var i = 0; i < keys.length; i++) {
                var key = keys[i];
                // Only write keys that are in the EXPORT_KEYS array for safety
                if (EXPORT_KEYS.indexOf(key) !== -1) {
                    localStorage.setItem(key, JSON.stringify(data[key]));
                }
            }

            resolve();
            location.reload();
        };

        reader.onerror = function() {
            alert('Import failed: Could not read the file.');
            reject(new Error('File read error'));
        };

        reader.readAsText(file);
    });
}

