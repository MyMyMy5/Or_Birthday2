// ==================== DRAG AND DROP ====================

/**
 * Sets up drag-and-drop file handling for a media section.
 * Creates a drop-zone overlay and manages dragenter/dragleave/drop events.
 * Uses a drag counter to handle nested element enter/leave correctly.
 * @param {HTMLElement} sectionElement - The section container element
 * @param {string} section - The section identifier (e.g. 'photos', 'songs')
 * @param {Function} reRender - Callback to re-render the section after adding files
 */
function setupDragAndDrop(sectionElement, section, reRender) {
    if (!sectionElement) return;

    // Create the overlay element
    const overlay = document.createElement('div');
    overlay.className = 'drop-zone-overlay';
    overlay.textContent = 'Drop files here';
    sectionElement.appendChild(overlay);

    let dragCounter = 0;

    sectionElement.addEventListener('dragenter', (e) => {
        e.preventDefault();
        // Only show overlay for external file drops, not internal reorder drags
        if (!e.dataTransfer || !Array.from(e.dataTransfer.types).includes('Files')) return;
        dragCounter++;
        sectionElement.classList.add('drag-active');
    });

    sectionElement.addEventListener('dragover', (e) => {
        e.preventDefault();
    });

    sectionElement.addEventListener('dragleave', (e) => {
        e.preventDefault();
        // Only decrement for external file drops
        if (!e.dataTransfer || !Array.from(e.dataTransfer.types).includes('Files')) return;
        dragCounter--;
        if (dragCounter <= 0) {
            dragCounter = 0;
            sectionElement.classList.remove('drag-active');
        }
    });

    // Safety net: reset overlay state when any drag ends
    sectionElement.addEventListener('dragend', (e) => {
        dragCounter = 0;
        sectionElement.classList.remove('drag-active');
    });

    sectionElement.addEventListener('drop', (e) => {
        e.preventDefault();
        dragCounter = 0;
        sectionElement.classList.remove('drag-active');

        const files = e.dataTransfer && e.dataTransfer.files;
        if (files && files.length > 0) {
            MediaManager.addMedia(section, files).then(() => {
                reRender();
            });
        }
    });
}

// ==================== TRASH PANEL ====================

/**
 * Sets up the trash modal panel.
 * Creates the modal DOM, wires open/close handlers, and provides
 * a renderTrashItems helper that fetches and displays deleted items.
 */
function setupTrashPanel() {
    // Create modal overlay
    const trashModal = document.createElement('div');
    trashModal.className = 'trash-modal';
    trashModal.id = 'trash-modal';
    trashModal.setAttribute('aria-hidden', 'true');

    trashModal.innerHTML = `
        <div class="trash-modal-content">
            <button class="trash-modal-close" aria-label="Close trash panel">&times;</button>
            <h2 class="trash-modal-title">🗑️ Deleted Items</h2>
            <div class="trash-list" id="trash-list"></div>
        </div>
    `;
    document.body.appendChild(trashModal);

    const trashList = trashModal.querySelector('#trash-list');
    const closeBtn = trashModal.querySelector('.trash-modal-close');
    const trashBtn = document.getElementById('trash-btn');

    // Section display names
    const sectionLabels = {
        photos: 'Photos',
        thingsYouLike: 'Things You Like',
        funnyMoments: 'Funny Moments',
        songs: 'Songs'
    };

    /**
     * Fetch trash items and render them inside the modal list.
     */
    function renderTrashItems() {
        MediaManager.getTrashItems().then(function (items) {
            // In server mode, also include URL-added items from localStorage trash
            if (MediaManager.getMode() === 'server') {
                var localTrash = JSON.parse(localStorage.getItem(MediaManager.STORAGE_KEYS.TRASH) || '[]');
                var urlTrashItems = localTrash.filter(function (entry) {
                    return entry.origin === 'url-added';
                });
                items = items.concat(urlTrashItems);
            }

            trashList.innerHTML = '';

            if (!items || items.length === 0) {
                const emptyMsg = document.createElement('p');
                emptyMsg.className = 'trash-empty';
                emptyMsg.textContent = 'No deleted items';
                trashList.appendChild(emptyMsg);
                return;
            }

            items.forEach(function (entry) {
                const card = document.createElement('div');
                card.className = 'trash-item-card';

                // Thumbnail
                const thumb = document.createElement('div');
                thumb.className = 'trash-item-thumb';
                // Build the image/video source for the thumbnail
                var thumbSrc = entry.source || '';
                if (!thumbSrc && entry.path) {
                    // Server mode: entry.path is relative to Deleted/, reconstruct the original path
                    thumbSrc = 'Deleted/' + entry.path;
                }
                var isAudio = (entry.type === 'audio' || entry.section === 'songs');
                var isVideo = (entry.type === 'video');
                if (isAudio) {
                    thumb.innerHTML = '<span class="trash-thumb-icon">🎵</span>';
                } else if (isVideo && entry.metadata && entry.metadata.videoId) {
                    thumb.style.backgroundImage = 'url(https://img.youtube.com/vi/' + entry.metadata.videoId + '/default.jpg)';
                    thumb.style.backgroundSize = 'cover';
                    thumb.style.backgroundPosition = 'center';
                } else if (thumbSrc) {
                    var thumbImg = document.createElement('img');
                    thumbImg.src = thumbSrc;
                    thumbImg.alt = '';
                    thumbImg.loading = 'lazy';
                    thumb.appendChild(thumbImg);
                } else {
                    thumb.innerHTML = '<span class="trash-thumb-icon">📄</span>';
                }

                const info = document.createElement('div');
                info.className = 'trash-item-info';

                const name = document.createElement('span');
                name.className = 'trash-item-name';
                // Show full filename if available, otherwise caption or id
                var displayName = entry.filename || entry.caption || entry.id || 'Untitled';
                name.textContent = displayName;

                const section = document.createElement('span');
                section.className = 'trash-item-section';
                section.textContent = sectionLabels[entry.section] || entry.section;

                info.appendChild(name);
                info.appendChild(section);

                const restoreBtn = document.createElement('button');
                restoreBtn.className = 'trash-restore-btn';
                restoreBtn.textContent = 'Restore';
                restoreBtn.addEventListener('click', function () {
                    MediaManager.restoreMedia(entry).then(function () {
                        renderTrashItems();
                    });
                });

                card.appendChild(thumb);
                card.appendChild(info);
                card.appendChild(restoreBtn);
                trashList.appendChild(card);
            });
        });
    }

    // Open modal
    if (trashBtn) {
        trashBtn.addEventListener('click', function () {
            trashModal.classList.add('active');
            trashModal.setAttribute('aria-hidden', 'false');
            renderTrashItems();
        });
    }

    // Close modal
    function closeTrashModal() {
        trashModal.classList.remove('active');
        trashModal.setAttribute('aria-hidden', 'true');
    }

    closeBtn.addEventListener('click', closeTrashModal);
    trashModal.addEventListener('click', function (e) {
        if (e.target === trashModal) closeTrashModal();
    });
    document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape' && trashModal.classList.contains('active')) {
            closeTrashModal();
        }
    });
}

// ==================== ENVELOPE TOGGLE ====================

/**
 * Sets up the envelope on/off toggle.
 * When off, the envelope page is skipped and the user goes straight to memories.
 * Preference is persisted in localStorage under 'envelope_enabled'.
 */
function setupEnvelopeToggle() {
    const toggle = document.getElementById('envelope-toggle');
    if (!toggle) return;

    // Read saved preference (default: enabled / checked)
    var saved = null;
    try { saved = localStorage.getItem('envelope_enabled'); } catch (e) { /* ignore */ }

    if (saved === 'false') {
        // Envelope disabled — skip straight to memories
        toggle.checked = false;
        envelopePage.classList.remove('active');
        memoriesPage.classList.add('active');
        setupSectionObserver();
        window.scrollTo(0, 0);
        // Hide the back-to-letter button
        if (backBtn) backBtn.style.display = 'none';
    }

    toggle.addEventListener('change', function () {
        try {
            localStorage.setItem('envelope_enabled', toggle.checked ? 'true' : 'false');
        } catch (e) { /* ignore */ }

        if (!toggle.checked) {
            // Switching off — if currently on envelope page, jump to memories
            if (envelopePage.classList.contains('active')) {
                envelopePage.classList.remove('active');
                memoriesPage.classList.add('active');
                setupSectionObserver();
                window.scrollTo(0, 0);
            }
            if (backBtn) backBtn.style.display = 'none';
        } else {
            // Switching on — show the back button again
            if (backBtn) backBtn.style.display = '';
        }
    });
}

