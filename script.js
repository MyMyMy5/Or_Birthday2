/**
 * Updates the visual state of the Undo and Redo buttons based on the HistoryStack.
 * Disables buttons (opacity + cursor) when their respective stack is empty.
 */
function updateUndoRedoButtons() {
    var undoBtn = document.getElementById('undo-btn');
    var redoBtn = document.getElementById('redo-btn');
    if (!undoBtn || !redoBtn) return;

    if (HistoryStack.canUndo()) {
        undoBtn.disabled = false;
        undoBtn.classList.remove('undo-redo-disabled');
    } else {
        undoBtn.disabled = true;
        undoBtn.classList.add('undo-redo-disabled');
    }

    if (HistoryStack.canRedo()) {
        redoBtn.disabled = false;
        redoBtn.classList.remove('undo-redo-disabled');
    } else {
        redoBtn.disabled = true;
        redoBtn.classList.add('undo-redo-disabled');
    }
}

/**
 * Performs an undo action: calls HistoryStack.undo() and applies the operation.
 */
function performUndo() {
    var operation = HistoryStack.undo();
    if (operation && typeof window.applyUndoOperation === 'function') {
        window.applyUndoOperation(operation);
    }
    updateUndoRedoButtons();
}

/**
 * Performs a redo action: calls HistoryStack.redo() and applies the operation.
 */
function performRedo() {
    var operation = HistoryStack.redo();
    if (operation && typeof window.applyRedoOperation === 'function') {
        window.applyRedoOperation(operation);
    }
    updateUndoRedoButtons();
}

