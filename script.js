var CUSTOM_SECTIONS_STORAGE_KEY = 'custom_sections';

/**
 * Generate a unique ID for a custom section.
 * @returns {string} A unique ID string.
 */
function generateCustomSectionId() {
    return 'custom-' + Date.now() + '-' + Math.random().toString(36).substr(2, 9);
}

/**
 * Retrieve all custom sections from localStorage.
 * @returns {Array} Array of custom section definition objects.
 */
function getCustomSections() {
    try {
        var raw = localStorage.getItem(CUSTOM_SECTIONS_STORAGE_KEY);
        return raw ? JSON.parse(raw) : [];
    } catch (e) {
        return [];
    }
}

/**
 * Add a new custom section with the given title, layout, and item type.
 * Persists to localStorage and returns the new section object.
 * @param {string} title - The section title (required, non-empty).
 * @param {string} layout - 'grid' or 'list'.
 * @param {string} itemType - 'text', 'image', or 'link'.
 * @returns {Object|null} The new section object, or null if invalid input.
 */
function addCustomSection(title, layout, itemType) {
    if (!title || typeof title !== 'string' || title.trim() === '') return null;
    var validLayouts = ['grid', 'list'];
    var validItemTypes = ['text', 'image', 'link'];
    if (validLayouts.indexOf(layout) === -1) return null;
    if (validItemTypes.indexOf(itemType) === -1) return null;

    var section = {
        id: generateCustomSectionId(),
        title: title.trim(),
        layout: layout,
        itemType: itemType,
        items: []
    };

    try {
        var sections = getCustomSections();
        sections.push(section);
        localStorage.setItem(CUSTOM_SECTIONS_STORAGE_KEY, JSON.stringify(sections));
    } catch (e) {
        // Silently fail on localStorage errors
    }

    return section;
}

/**
 * Delete a custom section by its ID.
 * Removes from localStorage and returns true if found and deleted.
 * @param {string} sectionId - The ID of the section to delete.
 * @returns {boolean} True if the section was found and deleted.
 */
function deleteCustomSection(sectionId) {
    if (!sectionId) return false;
    try {
        var sections = getCustomSections();
        var originalLength = sections.length;
        var filtered = sections.filter(function (s) { return s.id !== sectionId; });
        if (filtered.length === originalLength) return false;
        localStorage.setItem(CUSTOM_SECTIONS_STORAGE_KEY, JSON.stringify(filtered));
        return true;
    } catch (e) {
        return false;
    }
}

/**
 * Add an item to a custom section's items array.
 * @param {string} sectionId - The ID of the section to add the item to.
 * @param {Object} item - The item object to add (should have id and content at minimum).
 * @returns {boolean} True if the item was added successfully.
 */
function addItemToCustomSection(sectionId, item) {
    if (!sectionId || !item) return false;
    try {
        var sections = getCustomSections();
        var found = false;
        for (var i = 0; i < sections.length; i++) {
            if (sections[i].id === sectionId) {
                if (!Array.isArray(sections[i].items)) {
                    sections[i].items = [];
                }
                sections[i].items.push(item);
                found = true;
                break;
            }
        }
        if (!found) return false;
        localStorage.setItem(CUSTOM_SECTIONS_STORAGE_KEY, JSON.stringify(sections));
        return true;
    } catch (e) {
        return false;
    }
}

/**
 * Render a single custom section into the DOM.
 * @param {Object} sectionDef - The section definition object.
 * @returns {HTMLElement} The created section element.
 */
function renderCustomSection(sectionDef) {
    var sectionEl = document.createElement('div');
    sectionEl.className = 'section custom-section';
    sectionEl.id = 'custom-section-' + sectionDef.id;
    sectionEl.setAttribute('data-custom-section-id', sectionDef.id);

    var titleEl = document.createElement('h2');
    titleEl.className = 'section-title';
    titleEl.textContent = sectionDef.title;
    sectionEl.appendChild(titleEl);

    var itemsContainer = document.createElement('div');
    itemsContainer.className = 'custom-section-items';
    if (sectionDef.layout === 'grid') {
        itemsContainer.classList.add('custom-section-grid');
    } else {
        itemsContainer.classList.add('custom-section-list');
    }
    itemsContainer.setAttribute('data-item-type', sectionDef.itemType);

    // Render existing items
    if (Array.isArray(sectionDef.items)) {
        sectionDef.items.forEach(function (item) {
            var itemEl = renderCustomSectionItem(item, sectionDef.itemType);
            if (itemEl) {
                itemsContainer.appendChild(itemEl);
            }
        });
    }

    // Add Item button (visible in Edit Mode only)
    var addItemBtn = createCustomSectionAddButton(sectionDef.id, sectionDef.itemType, itemsContainer);
    itemsContainer.appendChild(addItemBtn);

    sectionEl.appendChild(itemsContainer);

    // Delete Section button (visible in Edit Mode only)
    var deleteBtn = document.createElement('button');
    deleteBtn.className = 'custom-section-delete-btn';
    deleteBtn.textContent = '🗑️ Delete Section';
    deleteBtn.addEventListener('click', function () {
        if (confirm('Are you sure you want to delete the section "' + sectionDef.title + '"? This cannot be undone.')) {
            deleteCustomSection(sectionDef.id);
            sectionEl.parentNode.removeChild(sectionEl);
        }
    });
    sectionEl.appendChild(deleteBtn);

    // Make section visible (match built-in section animation pattern)
    setTimeout(function () {
        sectionEl.classList.add('visible');
    }, 100);

    return sectionEl;
}

