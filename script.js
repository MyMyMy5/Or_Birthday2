/**
 * Shows a modal prompting the user to enter a URL and optional caption
 * to add media to the given section.
 * @param {string} section - The target section identifier
 */
function showUrlPrompt(section) {
    // Create modal overlay
    var modal = document.createElement('div');
    modal.className = 'url-prompt-modal';

    var content = document.createElement('div');
    content.className = 'url-prompt-content';

    var title = document.createElement('h3');
    title.textContent = 'Add via URL';

    var urlInput = document.createElement('input');
    urlInput.type = 'url';
    urlInput.placeholder = 'Paste URL here...';
    urlInput.className = 'url-input';

    var captionInput = document.createElement('input');
    captionInput.type = 'text';
    captionInput.placeholder = 'Caption (optional)';
    captionInput.className = 'caption-input';

    var errorDiv = document.createElement('div');
    errorDiv.className = 'url-error';
    errorDiv.style.display = 'none';

    var actions = document.createElement('div');
    actions.className = 'url-prompt-actions';

    var cancelBtn = document.createElement('button');
    cancelBtn.className = 'url-cancel-btn';
    cancelBtn.textContent = 'Cancel';

    var addBtn = document.createElement('button');
    addBtn.className = 'url-add-btn';
    addBtn.textContent = 'Add';

    actions.appendChild(cancelBtn);
    actions.appendChild(addBtn);

    content.appendChild(title);
    content.appendChild(urlInput);
    content.appendChild(captionInput);
    content.appendChild(errorDiv);
    content.appendChild(actions);
    modal.appendChild(content);
    document.body.appendChild(modal);

    // Focus the URL input
    setTimeout(function () { urlInput.focus(); }, 50);

    function closeModal() {
        if (modal.parentNode) {
            modal.parentNode.removeChild(modal);
        }
    }

    function handleSubmit() {
        var url = urlInput.value.trim();
        var caption = captionInput.value.trim();

        // If URL is empty, just close
        if (!url) {
            closeModal();
            return;
        }

        // Try to add via MediaManager
        MediaManager.addMediaByUrl(section, url, caption || undefined)
            .then(function () {
                closeModal();
            })
            .catch(function (err) {
                errorDiv.textContent = typeof err === 'string' ? err : 'Please enter a valid web address (http:// or https://)';
                errorDiv.style.display = 'block';
            });
    }

    cancelBtn.addEventListener('click', closeModal);
    addBtn.addEventListener('click', handleSubmit);

    // Close on overlay click
    modal.addEventListener('click', function (e) {
        if (e.target === modal) closeModal();
    });

    // Close on Escape, submit on Enter
    modal.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') closeModal();
        if (e.key === 'Enter') handleSubmit();
    });
}

