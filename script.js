    if (currentMode === 'grid') {
        gridBtn.classList.add('active');
        listBtn.classList.remove('active');
    } else {
        listBtn.classList.add('active');
        gridBtn.classList.remove('active');
    }

    gridBtn.addEventListener('click', function () {
        var layouts = getSectionLayouts();
        var oldLayout = layouts[sectionId] || null;
        applySectionLayout(sectionId, 'grid');
        layouts[sectionId] = 'grid';
        saveSectionLayouts(layouts);
        gridBtn.classList.add('active');
        listBtn.classList.remove('active');
        // Show column selector when switching to grid
        updateColumnSelectorVisibility(panel, sectionId);
        recordEditOperation('layout-change', sectionId, 'section_layouts', oldLayout, 'grid');
    });

