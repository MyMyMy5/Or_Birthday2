var PHOTO_FILTERS_STORAGE_KEY = 'photo_filters';

/**
 * Clamp a filter value to its allowed bounds.
 * @param {string} key - The filter property name.
 * @param {number} value - The value to clamp.
 * @returns {number} The clamped value.
 */
function clampFilterValue(key, value) {
    var bounds = {
        grayscale: { min: 0, max: 100 },
        sepia: { min: 0, max: 100 },
        brightness: { min: 50, max: 200 },
        contrast: { min: 50, max: 200 }
    };
    var b = bounds[key];
    if (!b) return value;
    return Math.max(b.min, Math.min(b.max, value));
}

/**
 * Retrieve all persisted photo filter values.
 * @returns {Object} Map of photoItemId → { grayscale, sepia, brightness, contrast }
 */
function getPhotoFilters() {
    try {
        var raw = localStorage.getItem(PHOTO_FILTERS_STORAGE_KEY);
        return raw ? JSON.parse(raw) : {};
    } catch (e) {
        return {};
    }
}

/**
 * Persist filter values for a specific photo item.
 * Values are clamped to their allowed bounds before storing.
 * @param {string} itemId - The photo item ID.
 * @param {Object} filterValues - { grayscale: 0-100, sepia: 0-100, brightness: 50-200, contrast: 50-200 }
 */
function setPhotoFilter(itemId, filterValues) {
    try {
        var store = getPhotoFilters();
        var clamped = {
            grayscale: clampFilterValue('grayscale', filterValues.grayscale),
            sepia: clampFilterValue('sepia', filterValues.sepia),
            brightness: clampFilterValue('brightness', filterValues.brightness),
            contrast: clampFilterValue('contrast', filterValues.contrast)
        };
        store[itemId] = clamped;
        localStorage.setItem(PHOTO_FILTERS_STORAGE_KEY, JSON.stringify(store));
    } catch (e) {
        // Silently fail on localStorage errors
    }
}

/**
 * Remove persisted filter values for a specific photo item.
 * @param {string} itemId - The photo item ID.
 */
function removePhotoFilter(itemId) {
    try {
        var store = getPhotoFilters();
        delete store[itemId];
        localStorage.setItem(PHOTO_FILTERS_STORAGE_KEY, JSON.stringify(store));
    } catch (e) {
        // Silently fail on localStorage errors
    }
}

/**
 * Apply CSS filter property to an image element based on filter values.
 * @param {HTMLElement} imgElement - The image element to apply filters to.
 * @param {Object} filterValues - { grayscale: 0-100, sepia: 0-100, brightness: 50-200, contrast: 50-200 }
 */
function applyFilterToElement(imgElement, filterValues) {
    if (!imgElement || !filterValues) return;
    var grayscale = clampFilterValue('grayscale', filterValues.grayscale);
    var sepia = clampFilterValue('sepia', filterValues.sepia);
    var brightness = clampFilterValue('brightness', filterValues.brightness);
    var contrast = clampFilterValue('contrast', filterValues.contrast);
    imgElement.style.filter = 'grayscale(' + grayscale + '%) sepia(' + sepia + '%) brightness(' + brightness + '%) contrast(' + contrast + '%)';
}

/**
 * Apply saved photo filters to all rendered photo elements on the page.
 * Iterates photo cards with data-id attributes and applies persisted filter values.
 */
function applySavedPhotoFilters() {
    var filters = getPhotoFilters();
    var filterIds = Object.keys(filters);
    if (filterIds.length === 0) return;

    filterIds.forEach(function (itemId) {
        var card = document.querySelector('.photo-card[data-id="' + itemId + '"]');
        if (!card) return;
        var img = card.querySelector('img');
        if (img) {
            applyFilterToElement(img, filters[itemId]);
        }
    });
}

