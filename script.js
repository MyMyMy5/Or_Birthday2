/**
 * Sanitizes an HTML string, keeping only allowed tags and attributes.
 * Allowed tags: <strong>, <em>, <a>, <ul>, <li>, <br>
 * Allowed attributes: only href on <a> tags
 * All other tags are replaced with their text content.
 * @param {string} html - The HTML string to sanitize
 * @returns {string} The sanitized HTML string
 */
function sanitizeHtml(html) {
    if (!html || typeof html !== 'string') return '';

    var ALLOWED_TAGS = ['strong', 'em', 'a', 'ul', 'li', 'br'];

    // Parse the HTML into a DOM tree
    var parser = new DOMParser();
    var doc = parser.parseFromString('<div>' + html + '</div>', 'text/html');
    var container = doc.body.firstChild;

    /**
     * Recursively processes a DOM node, keeping only allowed elements.
     * @param {Node} node - The DOM node to process
     * @returns {string} The sanitized HTML string for this node
     */
    function processNode(node) {
        if (node.nodeType === 3) {
            // Text node - return escaped text content
            return node.textContent;
        }

        if (node.nodeType !== 1) {
            // Not an element node - skip
            return '';
        }

        var tagName = node.tagName.toLowerCase();

        if (ALLOWED_TAGS.indexOf(tagName) === -1) {
            // Tag not allowed - return only its children's content
            var childContent = '';
            for (var i = 0; i < node.childNodes.length; i++) {
                childContent += processNode(node.childNodes[i]);
            }
            return childContent;
        }

        // Tag is allowed - build the sanitized element
        var result = '<' + tagName;

        // Only allow href attribute on <a> tags
        if (tagName === 'a' && node.hasAttribute('href')) {
            var href = node.getAttribute('href');
            result += ' href="' + href.replace(/"/g, '&quot;') + '"';
        }

        // Self-closing tags
        if (tagName === 'br') {
            result += '>';
            return result;
        }

        result += '>';

        // Process children
        for (var i = 0; i < node.childNodes.length; i++) {
            result += processNode(node.childNodes[i]);
        }

        result += '</' + tagName + '>';
        return result;
    }

    // Process all children of the container
    var output = '';
    for (var i = 0; i < container.childNodes.length; i++) {
        output += processNode(container.childNodes[i]);
    }

    return output;
}

// Expose sanitizeHtml on window for testability
if (typeof window !== 'undefined') {
    window.sanitizeHtml = sanitizeHtml;
}

/**
 * Creates a rich text editor with formatting toolbar for a given item.
 * @param {string} itemId - The item identifier
 * @param {string} existingHtml - Existing HTML content to pre-populate
 * @returns {HTMLElement} Container element with toolbar and contenteditable div
 */
function createRichTextEditor(itemId, existingHtml) {
    // Container
    var container = document.createElement('div');
    container.className = 'rich-text-editor';
    container.setAttribute('data-editor-item-id', itemId);

    // Toolbar
    var toolbar = document.createElement('div');
    toolbar.className = 'rich-text-toolbar';

    // Bold button
    var boldBtn = document.createElement('button');
    boldBtn.type = 'button';
    boldBtn.className = 'rte-btn rte-bold';
    boldBtn.textContent = 'B';
    boldBtn.title = 'Bold (Ctrl+B)';
    boldBtn.addEventListener('mousedown', function (e) {
        e.preventDefault();
        document.execCommand('bold', false, null);
        editorDiv.focus();
    });

    // Italic button
    var italicBtn = document.createElement('button');
    italicBtn.type = 'button';
    italicBtn.className = 'rte-btn rte-italic';
    italicBtn.textContent = 'I';
    italicBtn.title = 'Italic (Ctrl+I)';
    italicBtn.addEventListener('mousedown', function (e) {
        e.preventDefault();
        document.execCommand('italic', false, null);
        editorDiv.focus();
    });

    // Link button
    var linkBtn = document.createElement('button');
    linkBtn.type = 'button';
    linkBtn.className = 'rte-btn rte-link';
    linkBtn.textContent = '🔗';
    linkBtn.title = 'Insert Link';
    linkBtn.addEventListener('mousedown', function (e) {
        e.preventDefault();
        var url = prompt('Enter URL:');
        if (url) {
            document.execCommand('createLink', false, url);
        }
        editorDiv.focus();
    });

    // Bullet List button
    var listBtn = document.createElement('button');
    listBtn.type = 'button';
    listBtn.className = 'rte-btn rte-list';
    listBtn.textContent = '•';
    listBtn.title = 'Bullet List';
    listBtn.addEventListener('mousedown', function (e) {
        e.preventDefault();
        document.execCommand('insertUnorderedList', false, null);
        editorDiv.focus();
    });

    toolbar.appendChild(boldBtn);
    toolbar.appendChild(italicBtn);
    toolbar.appendChild(linkBtn);
    toolbar.appendChild(listBtn);

    // Contenteditable editing surface
    var editorDiv = document.createElement('div');
    editorDiv.className = 'rich-text-content';
    editorDiv.setAttribute('contenteditable', 'true');
    editorDiv.setAttribute('data-placeholder', 'Type your note here...');

    // Pre-populate with sanitized existing HTML
    if (existingHtml) {
        editorDiv.innerHTML = sanitizeHtml(existingHtml);
    }

    // Keyboard shortcuts
    editorDiv.addEventListener('keydown', function (e) {
        if (e.ctrlKey || e.metaKey) {
            if (e.key === 'b' || e.key === 'B') {
                e.preventDefault();
                document.execCommand('bold', false, null);
            } else if (e.key === 'i' || e.key === 'I') {
                e.preventDefault();
                document.execCommand('italic', false, null);
            }
        }
    });

    // Paste event handler - sanitize pasted content
    editorDiv.addEventListener('paste', function (e) {
        e.preventDefault();
        var clipboardData = e.clipboardData || (typeof window !== 'undefined' && window.clipboardData);
        if (!clipboardData) return;

        var pastedHtml = clipboardData.getData('text/html');
        var pastedText = clipboardData.getData('text/plain');

        var contentToInsert;
        if (pastedHtml) {
            contentToInsert = sanitizeHtml(pastedHtml);
        } else if (pastedText) {
            // Convert plain text line breaks to <br>
            contentToInsert = pastedText.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\n/g, '<br>');
        } else {
            return;
        }

        document.execCommand('insertHTML', false, contentToInsert);
    });

    container.appendChild(toolbar);
    container.appendChild(editorDiv);

    return container;
}

